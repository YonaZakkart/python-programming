# COLA FIFO = First In, First Out (el primero en entrar es el primero en salir)

# Una lista de Python puede representar una cola
cola = []

# ENQUEUE (encolar): agregamos elementos al final de la cola
cola.append('Ana')
cola.append('Carlos')
cola.append('Luis')

# Mostramos el contenido de la cola
print("Contenido de la cola:", cola)
